-- (F4) remove espaços no fim das linhas, como no vimrc antigo
vim.keymap.set("n", "<F4>", function()
  local view = vim.fn.winsaveview()
  vim.cmd([[keeppatterns %s/\s\+$//e]])
  vim.fn.winrestview(view)
end, { desc = "Remove trailing whitespace" })
